def celsius_ke_fahrenheit(c):
    """Mengkonversi suhu dari Celsius ke Fahrenheit."""
    return c * 9 / 5 + 32


def fahrenheit_ke_celsius(f):
    """Mengkonversi suhu dari Fahrenheit ke Celsius."""
    return (f - 32) * 5 / 9


def km_ke_mil(km):
    """Mengkonversi jarak dari kilometer ke mil."""
    return km * 0.621371
